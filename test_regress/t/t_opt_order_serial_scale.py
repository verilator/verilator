import re
import tempfile

import vltest_bootstrap

test.scenarios('vlt')

if test.have_dev_gcov:
    test.skip("Too slow with code coverage")
if test.have_dev_asan or test.tsan:
    test.skip("Too slow with sanitizers")

test.top_filename = test.obj_dir + "/" + test.name + ".v"

# Retained instances each have a distinct clock domain. Exhausting a ready scope must not
# search all other ready domains for another scope. Only measures NBA scheduling, not model builds.
SIZE_SMALL = 8000
SIZE_LARGE = SIZE_SMALL * 4
# Linear scaling gives 4x, quadratic gives 16x
MAX_RATIO = 8
# Ignore the ratio when scheduling is fast enough that timer noise dominates
MIN_SECONDS = 0.5


def gen(filename, n):
    with open(filename, 'w', encoding="utf8") as fh:
        fh.write(f"// Generated by {test.name}.py\n")
        fh.write("module leaf (input clk, input [30:0] d, output logic [30:0] q);\n")
        fh.write("  /*verilator no_inline_module*/\n")
        fh.write("  always_ff @(posedge clk) q <= d;\n")
        fh.write("endmodule\n")
        fh.write(f"module t (input clk[{n}], input [30:0] d, output [30:0] q[{n}]);\n")
        for i in range(n):
            fh.write(f"  leaf u{i} (.clk(clk[{i}]), .d(d), .q(q[{i}]));\n")
        fh.write("endmodule\n")


def sched_seconds(n):
    gen(test.top_filename, n)
    # Measure each size in a fresh directory, independent of earlier output or prior test runs.
    mdir = tempfile.mkdtemp(prefix=str(n) + "_", dir=test.obj_dir)
    test.compile(verilator_flags2=["--stats", "--no-debug-check", "--Mdir", mdir],
                 threads=1,
                 make_main=False,
                 verilator_make_gmake=False)
    stats_filename = mdir + "/" + test.vm_prefix + "__stats.txt"
    with open(stats_filename, 'r', encoding="utf8") as fh:
        stats = fh.read()
    times = re.findall(r'Stage, Elapsed time \(sec\), \d+_sched-create-nba\s+(\S+)', stats)
    if not times:
        test.error("NBA scheduling elapsed time not found in " + stats_filename)
    return sum(float(t) for t in times)


small = sched_seconds(SIZE_SMALL)
large = sched_seconds(SIZE_LARGE)
if large > MIN_SECONDS and large > small * MAX_RATIO:
    test.error("Serial ordering time scaled superlinearly with clock domains: " +
               f"{SIZE_SMALL} domains took {small:.3f}s, " +
               f"{SIZE_LARGE} domains took {large:.3f}s (over {MAX_RATIO}x)")

test.passes()
