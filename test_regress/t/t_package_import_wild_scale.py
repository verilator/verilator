import vltest_bootstrap

test.scenarios('vlt')

N_SPECIALIZATIONS = 20
N_SYMBOLS_SMALL = 10
N_SYMBOLS_LARGE = 1000


def imported_symbols(n_symbols):
    # In a directory of its own, as file_grep() caches the contents of each file it reads
    mdir = test.obj_dir + "/obj_" + str(n_symbols)
    test.mkdir_ok(mdir)
    test.top_filename = mdir + "/t_package_import_wild_scale.sv"
    with open(test.top_filename, 'w', encoding="utf8") as fh:
        fh.write("// Generated by t_package_import_wild_scale.py\n")
        fh.write("package big_pkg;\n")
        for i in range(n_symbols):
            fh.write("  localparam int P_{0} = {0};\n".format(i))
        fh.write("endpackage\n\n")
        fh.write("module leaf #(parameter int W = 1) (output logic [W-1:0] q);\n")
        fh.write("  import big_pkg::*;\n")
        fh.write("  assign q = W'(P_0);\n")
        fh.write("endmodule\n\n")
        fh.write("module t;\n")
        fh.write("  for (genvar g = 1; g <= {}; g++) begin : g_leaf\n".format(N_SPECIALIZATIONS))
        fh.write("    logic [g-1:0] q;\n")
        fh.write("    leaf #(.W(g)) u_leaf (.q(q));\n")
        fh.write("  end\n")
        fh.write("endmodule\n")
    test.lint(verilator_flags2=["--stats", "-Mdir", mdir])
    stats_filename = mdir + "/V" + test.name + "__stats.txt"
    return int(test.file_grep(stats_filename, r'LinkDot, Imported symbols\s+(\d+)')[0])


small_imported = imported_symbols(N_SYMBOLS_SMALL)
large_imported = imported_symbols(N_SYMBOLS_LARGE)
if large_imported != small_imported:
    test.error("Imported symbols grew with package size: " +
               f"{N_SYMBOLS_SMALL} package symbols imported {small_imported}, " +
               f"{N_SYMBOLS_LARGE} package symbols imported {large_imported}")

test.passes()
