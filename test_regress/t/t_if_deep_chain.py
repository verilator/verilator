import vltest_bootstrap

test.scenarios('vlt')
test.top_filename = os.path.join(test.obj_dir, "t_if_deep_chain.v")

# Each else-if level holds several parser stack entries; 2000 levels used to
# exhaust a 10000 entry stack
levels = 2000


def gen(filename):
    with open(filename, 'w', encoding="utf8") as fh:
        fh.write("// Generated by t_if_deep_chain.py\n")
        fh.write("module t (\n    input logic [15:0] a,\n    output logic [15:0] y\n);\n")
        fh.write("  always_comb begin\n")
        fh.write("    if (a == 16'd0) y = 16'd0;\n")
        for i in range(1, levels):
            fh.write("    else if (a == 16'd" + str(i) + ") y = 16'd" + str(i * 7) + ";\n")
        fh.write("    else y = 16'hffff;\n")
        fh.write("  end\n")
        fh.write("endmodule\n")


gen(test.top_filename)

test.lint()

test.passes()
